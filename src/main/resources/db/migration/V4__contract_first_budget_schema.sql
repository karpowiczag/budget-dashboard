CREATE INDEX idx_monthly_report_month ON report_monthly_summaries (report_year, month_key);
CREATE INDEX idx_categories_report_spend ON report_category_summaries (report_year, spend DESC);
CREATE INDEX idx_hierarchy_report_area ON report_hierarchy_summaries (report_year, budget_area, budget_group, category);
CREATE INDEX idx_budget_transactions_year_month ON budget_transactions (report_year, month_key);
CREATE INDEX idx_budget_transactions_year_posted_date ON budget_transactions (report_year, posted_date);
CREATE INDEX idx_budget_transactions_year_category ON budget_transactions (report_year, corrected_category);
CREATE INDEX idx_budget_transactions_year_subcategory ON budget_transactions (report_year, corrected_category, subcategory);
CREATE INDEX idx_budget_transactions_year_bucket ON budget_transactions (report_year, budget_bucket);
