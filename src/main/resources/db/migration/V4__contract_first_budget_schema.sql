CREATE TABLE report_large_oneoffs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_year INTEGER NOT NULL REFERENCES reports (report_year) ON DELETE CASCADE,
    posted_date DATE NOT NULL,
    merchant VARCHAR(256) NOT NULL,
    category VARCHAR(160) NOT NULL,
    bucket VARCHAR(160) NOT NULL,
    amount NUMERIC(14,2) NOT NULL,
    month_key VARCHAR(7) NOT NULL,
    confidence VARCHAR(32) NOT NULL,
    description TEXT NOT NULL
);

CREATE TABLE budget_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_year INTEGER NOT NULL REFERENCES reports (report_year) ON DELETE CASCADE,
    lp INTEGER NOT NULL,
    posted_date DATE NOT NULL,
    month_key VARCHAR(7) NOT NULL,
    merchant VARCHAR(256),
    description TEXT,
    account VARCHAR(128),
    bank_category VARCHAR(160),
    corrected_category VARCHAR(160),
    budget_area VARCHAR(160),
    budget_group VARCHAR(160),
    subcategory VARCHAR(160),
    budget_bucket VARCHAR(160),
    fixedness VARCHAR(80),
    transaction_type VARCHAR(80),
    amount NUMERIC(14,2) NOT NULL,
    income NUMERIC(14,2) NOT NULL,
    analysis_spend NUMERIC(14,2) NOT NULL,
    discretionary NUMERIC(14,2) NOT NULL,
    excluded NUMERIC(14,2) NOT NULL,
    excluded_outgoing NUMERIC(14,2) NOT NULL,
    excluded_incoming NUMERIC(14,2) NOT NULL,
    excluded_net NUMERIC(14,2) NOT NULL,
    confidence VARCHAR(32),
    notes TEXT,
    matched_rule TEXT,
    UNIQUE (report_year, lp)
);

CREATE TABLE import_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_year INTEGER,
    input_csv VARCHAR(512),
    status VARCHAR(32) NOT NULL,
    message TEXT,
    duplicates_removed INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_reports_imported_at ON reports (imported_at DESC);
