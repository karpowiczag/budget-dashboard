CREATE TABLE reports (
    report_year INTEGER PRIMARY KEY,
    period_label VARCHAR(64) NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    input_csv VARCHAR(512),
    imported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    transaction_count INTEGER NOT NULL,
    income NUMERIC(14,2) NOT NULL,
    spend NUMERIC(14,2) NOT NULL
);

CREATE TABLE report_kpis (
    report_year INTEGER PRIMARY KEY REFERENCES reports (report_year) ON DELETE CASCADE,
    income NUMERIC(14,2) NOT NULL,
    spend NUMERIC(14,2) NOT NULL,
    discretionary NUMERIC(14,2) NOT NULL,
    operating_surplus NUMERIC(14,2) NOT NULL,
    savings_rate NUMERIC(10,4) NOT NULL,
    excluded_gross NUMERIC(14,2) NOT NULL,
    excluded_outgoing NUMERIC(14,2) NOT NULL,
    excluded_incoming NUMERIC(14,2) NOT NULL,
    excluded_net NUMERIC(14,2) NOT NULL,
    real_savings_outgoing NUMERIC(14,2) NOT NULL,
    unassigned_surplus NUMERIC(14,2) NOT NULL,
    transactions INTEGER NOT NULL,
    corrections INTEGER NOT NULL,
    low_confidence INTEGER NOT NULL,
    to_check INTEGER NOT NULL,
    to_check_amount NUMERIC(14,2) NOT NULL
);

CREATE TABLE report_monthly_summaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_year INTEGER NOT NULL REFERENCES reports (report_year) ON DELETE CASCADE,
    month_label VARCHAR(7) NOT NULL,
    month_key VARCHAR(7) NOT NULL,
    income NUMERIC(14,2) NOT NULL,
    spend NUMERIC(14,2) NOT NULL,
    discretionary NUMERIC(14,2) NOT NULL,
    excluded NUMERIC(14,2) NOT NULL,
    savings_investments NUMERIC(14,2) NOT NULL,
    net_flow NUMERIC(14,2) NOT NULL,
    savings_rate NUMERIC(10,4) NOT NULL,
    transactions INTEGER NOT NULL,
    spend_per_day NUMERIC(14,2) NOT NULL,
    UNIQUE (report_year, month_key)
);

CREATE TABLE report_category_summaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_year INTEGER NOT NULL REFERENCES reports (report_year) ON DELETE CASCADE,
    category VARCHAR(160) NOT NULL,
    budget_group VARCHAR(160) NOT NULL,
    spend NUMERIC(14,2) NOT NULL,
    income NUMERIC(14,2) NOT NULL,
    excluded NUMERIC(14,2) NOT NULL,
    monthly_average NUMERIC(14,2) NOT NULL,
    max_month VARCHAR(7),
    max_amount NUMERIC(14,2) NOT NULL,
    discretionary BOOLEAN NOT NULL,
    transaction_count INTEGER NOT NULL,
    UNIQUE (report_year, category)
);

CREATE TABLE report_hierarchy_summaries (
